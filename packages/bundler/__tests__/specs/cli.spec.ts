import { readdirSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { run } from '../../lib';
import { decorated, TempProject } from '../project';

class Io {
  readonly out: string[] = [];
  readonly err: string[] = [];

  constructor(
    readonly cwd: string,
    private readonly input?: string,
  ) {}

  stdout = (line: string) => this.out.push(line);
  stderr = (line: string) => this.err.push(line);
  stdin = () => this.input;
}

describe('Story: Describe the container in a config file (tic CLI)', () => {
  let project: TempProject;

  beforeEach(() => {
    project = TempProject.create({
      'tsconfig.json': { compilerOptions: { paths: { '@app/*': ['./src/*'] } } },
      'app.bundle.json': { paths: { include: ['@app/services'] } },
      'src/services/Logger.ts': decorated('Logger'),
    });
  });

  afterEach(() => project.dispose());

  it('prints the bundle the config file describes to stdout, and writes nothing', () => {
    const io = new Io(project.root);
    const before = readdirSync(project.root, { recursive: true });

    expect(run(['build', 'app.bundle.json'], io)).toBe(0);
    const bundle = io.out.join('\n');
    expect(bundle).toContain("import { Logger } from '@app/services/Logger';");
    expect(bundle).toContain('export class AppBundle implements IContainerModule');
    expect(readdirSync(project.root, { recursive: true })).toEqual(before);
  });

  it('prints exactly what build() returns, so `tic build app.bundle.json > out.ts` saves it as is', () => {
    const io = new Io(project.root);

    run(['build', 'app.bundle.json'], io);

    expect(`${io.out.join('\n')}\n`).toMatch(/^\/\/ Generated by `tic build`\. Do not edit by hand\.\n[\s\S]*\}\n$/);
    expect(io.out).toHaveLength(1);
  });

  it('reads a YAML config, resolving its paths against the config file', () => {
    project.write('config/prod.bundle.yml', "tsconfig: ../tsconfig.json\npaths:\n  include: ['../src']\n");
    const io = new Io(project.path('src'));

    expect(run(['build', '../config/prod.bundle.yml'], io)).toBe(0);
    expect(io.out.join('\n')).toContain('export class ProdBundle');
  });

  it('merges several configs left to right: tic build common.bundle.yml prod.bundle.yml > out.ts', () => {
    project.write('common.bundle.yml', "paths:\n  include: ['@app/services']\n");
    project.write('prod.bundle.yml', "importExtension: '.js'\n");
    const io = new Io(project.root);

    expect(run(['build', 'common.bundle.yml', 'prod.bundle.yml'], io)).toBe(0);
    expect(io.out.join('\n')).toContain("import { Logger } from '@app/services/Logger.js';");
    expect(io.out.join('\n')).toContain('export class ProdBundle implements IContainerModule');
  });

  it('names every merged config in an error', () => {
    project.write('common.bundle.yml', 'paths: {}\n');
    const io = new Io(project.root);

    expect(run(['build', 'common.bundle.yml', 'app.bundle.json', 'missing.bundle.yml'], io)).toBe(1);
    expect(io.err.join('\n')).toContain(
      'common.bundle.yml + app.bundle.json + missing.bundle.yml: config file not found',
    );
  });

  it.each([
    [['build', '-', 'app.bundle.json'], '- reads one config from stdin and cannot be combined with other arguments'],
    [['build', '-', 'src'], '- reads one config from stdin and cannot be combined with other arguments'],
    [['build', 'app.bundle.json', 'src'], 'config files cannot be combined with a tsconfig or paths'],
    [['build', 'app.bundle.json', 'tsconfig.json'], 'config files cannot be combined with a tsconfig or paths'],
    [['build', 'tsconfig.json', 'tsconfig.build.json'], 'name one tsconfig, not 2: tsconfig.json, tsconfig.build.json'],
    [['build', 'src/Missing.ts'], 'namespace "src/Missing.ts"'],
    [['build', 'app.bundle.json', '--output', 'x.ts'], "Unknown option '--output'"],
    [['build', 'app.bundle.json', '--check'], "Unknown option '--check'"],
    [['build', 'missing.bundle.json'], 'missing.bundle.json: config file not found'],
    [['build', 'app.bundle.toml'], 'expected a .json, .yaml or .yml config file'],
  ])('rejects %j', (argv, message) => {
    const io = new Io(project.root);

    expect(run(argv, io)).toBe(1);
    expect(io.out).toEqual([]);
    expect(io.err.join('\n')).toContain(message);
  });

  it('never builds from tsconfig.json alone: without an argument or piped config it fails', () => {
    const io = new Io(project.root);

    expect(run(['build'], io)).toBe(1);
    expect(io.out).toEqual([]);
    expect(io.err.join('\n')).toContain('missing <config>: name a config file, or pipe one in');
  });

  it('builds AppBundle of a tsconfig named alone: tic build tsconfig.json', () => {
    project.write('tsconfig.build.json', { compilerOptions: { paths: { '@infra/*': ['./src/infra/*'] } } });
    project.write('src/infra/Clock.ts', decorated('Clock'));
    const io = new Io(project.root);

    expect(run(['build', 'tsconfig.build.json'], io)).toBe(0);
    expect(io.out.join('\n')).toContain("import { Clock } from '@infra/Clock';");
    expect(io.out.join('\n')).not.toContain('Logger');
  });

  it.each([
    [['src/services/**/*.ts']],
    [['@app/**/Logger.ts']],
    [['src/services']],
    [['src/services/Logger.ts', 'src/services/Mailer.ts']],
  ])('builds AppBundle of the folders, files and globs %j it is given, relative to the working directory', (paths) => {
    project.write('src/services/Mailer.ts', decorated('Mailer'));
    project.write('src/infra/Clock.ts', decorated('Clock'));
    const io = new Io(project.root);

    expect(run(['build', ...paths], io)).toBe(0);
    const bundle = io.out.join('\n');
    expect(bundle).toContain('export class AppBundle implements IContainerModule');
    expect(bundle).toContain("import { Logger } from '@app/services/Logger';");
    expect(bundle).not.toContain('Clock');
  });

  it('scans the paths it is given through the aliases of a tsconfig named with them', () => {
    project.write('config/tsconfig.di.json', { compilerOptions: { paths: { '@di/*': ['../src/*'] } } });
    const io = new Io(project.root);

    expect(run(['build', 'config/tsconfig.di.json', 'src/services/*.ts'], io)).toBe(0);
    expect(io.out.join('\n')).toContain("import { Logger } from '@di/services/Logger';");
  });

  it('names the tsconfig and the paths in an error', () => {
    const io = new Io(project.root);

    expect(run(['build', 'tsconfig.json', 'lib/**/*.ts'], io)).toBe(1);
    expect(io.err.join('\n')).toContain('tsconfig.json + lib/**/*.ts: namespace "lib"');
  });

  it.each([
    [['build'], "name: app\npaths:\n  include: ['@app/services']\n"],
    [['build', '-'], "name: app\npaths:\n  include: ['@app/services']\n"],
    [['build'], JSON.stringify({ name: 'app', paths: { include: ['@app/services'] } })],
  ])('reads a piped config from stdin with %j: cat app.bundle.yml | tic build > out.ts', (argv, input) => {
    const io = new Io(project.root, input);

    expect(run(argv, io)).toBe(0);
    expect(io.out.join('\n')).toContain('export class AppBundle implements IContainerModule');
    expect(io.out.join('\n')).toContain("import { Logger } from '@app/services/Logger';");
  });

  it('resolves a piped config against the working directory', () => {
    const io = new Io(
      project.path('src'),
      "name: app\ntsconfig: ../tsconfig.json\npaths:\n  include: ['./services']\n",
    );

    expect(run(['build'], io)).toBe(0);
    expect(io.out.join('\n')).toContain('Registration.fromClass(Logger)');
  });

  it('requires a name in a piped config: there is no file name to take it from', () => {
    const io = new Io(project.root, "paths:\n  include: ['@app/services']\n");

    expect(run(['build'], io)).toBe(1);
    expect(io.err).toEqual(['tic: <stdin>: name: required for a config read from stdin']);
  });

  it('reports a config error on stderr, naming the config, and prints nothing', () => {
    project.write('app.bundle.json', { output: 'x.ts', paths: { include: ['@app/services'] } });
    const io = new Io(project.root);

    expect(run(['build', 'app.bundle.json'], io)).toBe(1);
    expect(io.out).toEqual([]);
    expect(io.err).toEqual(['tic: app.bundle.json: output: unknown field']);
  });

  it('fails when a selected class is not covered by a tsconfig alias', () => {
    project.write('app.bundle.json', { paths: { include: ['./lib'] } });
    project.write('lib/External.ts', decorated('External'));
    const io = new Io(project.root);

    expect(run(['build', 'app.bundle.json'], io)).toBe(1);
    expect(io.err.join('\n')).toContain('no tsconfig paths alias covers lib/External.ts');
  });

  it('prints warnings to stderr, never into the bundle on stdout', () => {
    project.write('app.bundle.json', { paths: { include: ['@app/services'], exclude: ['legacy/**'] } });
    const io = new Io(project.root);

    expect(run(['build', 'app.bundle.json'], io)).toBe(0);
    expect(io.err.join('\n')).toContain('tic: warning: app.bundle.json: paths.exclude');
    expect(io.err.at(-1)).toBe('Bundled AppBundle: 1 dependency from 1 file (1 warning)');
    expect(io.out.join('\n')).not.toContain('warning');
  });

  it('reports progress on stderr — the bundle, each class in it and a summary — never in the bundle on stdout', () => {
    project.write('app.bundle.json', { paths: { include: ['@app/services', './src/infra'] } });
    project.write('src/services/Mailer.ts', decorated('Mailer'));
    project.write('src/services/helpers.ts', 'export const noop = () => {};\n');
    project.write('src/infra/Clock.ts', decorated('Clock'));
    const io = new Io(project.root);

    expect(run(['build', 'app.bundle.json'], io)).toBe(0);
    expect(io.err).toEqual([
      'Bundling AppBundle...',
      '  Clock: src/infra/Clock.ts',
      '  Logger: src/services/Logger.ts',
      '  Mailer: src/services/Mailer.ts',
      'Bundled AppBundle: 3 dependencies from 3 files',
    ]);
    expect(io.out).toHaveLength(1);
  });

  it('prints a warning when two classes pass the same decorator token', () => {
    const source = (name: string) =>
      `import { register } from 'ts-ioc-container';\n@register(Token)\nexport class ${name} {}\n`;
    project.write('src/services/A.ts', source('A'));
    project.write('src/services/B.ts', source('B'));
    const io = new Io(project.root);

    expect(run(['build', 'app.bundle.json'], io)).toBe(0);
    expect(io.err.join('\n')).toContain('tic: warning: app.bundle.json: decorator token "Token"');
  });

  it('prints usage for --help and rejects an unknown command', () => {
    const io = new Io(project.root);

    expect(run(['--help'], io)).toBe(0);
    expect(io.out.join('\n')).toContain('ts-ioc-container build [<config>...]');
    expect(io.out.join('\n')).toContain("tic build 'src/**/*.service.ts'");
    expect(io.out.join('\n')).toContain('tic build app.bundle.json > src/di/app.bundle.ts');
    expect(io.out.join('\n')).toContain('tic is a shortcut for ts-ioc-container');
    expect(run(['compile'], io)).toBe(1);
    expect(io.err).toContain('tic: unknown command "compile"');
  });

  it('installs as ts-ioc-container, with tic as a shortcut to the same program', () => {
    const { bin } = JSON.parse(readFileSync(path.resolve(__dirname, '../../package.json'), 'utf8'));

    expect(bin).toEqual({ 'ts-ioc-container': 'cjm/bin.js', tic: 'cjm/bin.js' });
  });
});
