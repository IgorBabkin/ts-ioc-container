import { by, inject, register, SingleToken } from 'ts-ioc-container';
import { type IRenderService, IRenderServiceKey } from '../../../services/HandlebarsRenderService';
import type { DiscoveredClass } from '../domain/scan';

export interface BundleViewInput {
  /** Name of the generated class. */
  name: string;
  /** Shown in the header: the folders scanned. */
  paths: string[];
  classes: (DiscoveredClass & { specifier: string })[];
}

/** The first line of every generated bundle; marks it as output, never input. */
export const GENERATED_HEADER = '// Generated by `tic build`';

/** The protocol a bundle is rendered from. */
const BUNDLE_PROTOCOL = 'Bundle.ts.hbs';

const RUNTIME_IMPORTS = ['IContainer', 'IContainerModule', 'Registration'];

/** What `protocols/Bundle.ts.hbs` renders. */
interface BundleViewData {
  paths: string[];
  name: string;
  imports: { specifier: string; defaultName?: string; named: string[] }[];
  registrations: string[];
}

/** Turns the selected classes into the generated bundle's source. */
export interface IBundleView {
  /**
   * Renders the generated bundle — static imports, and the bundle registering each selected class.
   *
   * @throws {Error} when the bundle protocol is not registered.
   */
  render(input: BundleViewInput): string;
}

export const IBundleViewKey = new SingleToken<IBundleView>('IBundleView');

@register(IBundleViewKey)
export class BundleView implements IBundleView {
  constructor(@inject(by(IRenderServiceKey)) private readonly renderer: IRenderService) {}

  /**
   * @throws {Error} when the bundle protocol is not registered.
   */
  render(input: BundleViewInput): string {
    return this.renderer.render(BUNDLE_PROTOCOL, toData(input));
  }
}

/**
 * Prepares the data the bundle protocol renders: unique local names, and one import
 * per file in file order.
 */
function toData({ name, paths, classes }: BundleViewInput): BundleViewData {
  // `container` is the parameter of the generated `applyTo`, which would shadow an import of that name.
  const taken = new Set([...RUNTIME_IMPORTS, 'container', name]);
  const uniqueName = (wanted: string) => {
    let candidate = wanted;
    for (let n = 2; taken.has(candidate); n++) candidate = `${wanted}_${n}`;
    taken.add(candidate);
    return candidate;
  };

  // One import statement per file, in file order.
  const byFile = new Map<string, { specifier: string; defaultName?: string; named: string[] }>();
  const bindings = classes.map((cls) => {
    const binding = uniqueName(cls.localName);
    const entry = byFile.get(cls.file) ?? { specifier: cls.specifier, named: [] };
    byFile.set(cls.file, entry);
    if (cls.exportName === 'default') entry.defaultName = binding;
    else entry.named.push(binding === cls.exportName ? binding : `${cls.exportName} as ${binding}`);
    return binding;
  });

  return { paths, name, imports: [...byFile.values()], registrations: bindings };
}
