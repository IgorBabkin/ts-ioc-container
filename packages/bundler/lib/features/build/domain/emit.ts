import { renderProtocol } from '../../../services/HandlebarsRenderService';
import type { DiscoveredClass } from './scan';

export interface EmitInput {
  /** Name of the generated class. */
  name: string;
  /** Shown in the header: where the output came from. */
  configPath: string;
  /** The folders scanned; `undefined` when the files came from the extended tsconfig. */
  paths?: string[];
  /** Shown in the header when `paths` is `undefined`: the tsconfig the files came from. */
  tsconfigPath: string;
  classes: (DiscoveredClass & { specifier: string })[];
}

/** The first line of every generated bundle; marks it as output, never input. */
export const GENERATED_HEADER = '// Generated by `tic build`';

/** What `protocols/Bundle.ts.hbs` renders. */
export interface BundleView {
  configPath: string;
  paths?: string[];
  tsconfigPath: string;
  name: string;
  imports: { specifier: string; defaultName?: string; named: string[] }[];
  registrations: string[];
}

/** The protocol a bundle is rendered from. */
export const BUNDLE_PROTOCOL = 'Bundle.ts.hbs';

const RUNTIME_IMPORTS = ['IContainer', 'IContainerModule', 'IRegistration', 'Registration'];

/**
 * Prepares the data the bundle protocol renders: unique local names, and one import
 * per file in file order.
 */
export function bundleView({ name, configPath, paths, tsconfigPath, classes }: EmitInput): BundleView {
  const taken = new Set([...RUNTIME_IMPORTS, 'registrations', name]);
  const uniqueName = (wanted: string) => {
    let candidate = wanted;
    for (let n = 2; taken.has(candidate); n++) candidate = `${wanted}_${n}`;
    taken.add(candidate);
    return candidate;
  };

  // One import statement per file, in file order.
  const byFile = new Map<string, { specifier: string; defaultName?: string; named: string[] }>();
  const bindings = classes.map((cls) => {
    const binding = uniqueName(cls.localName);
    const entry = byFile.get(cls.file) ?? { specifier: cls.specifier, named: [] };
    byFile.set(cls.file, entry);
    if (cls.exportName === 'default') entry.defaultName = binding;
    else entry.named.push(binding === cls.exportName ? binding : `${cls.exportName} as ${binding}`);
    return binding;
  });

  return { configPath, paths, tsconfigPath, name, imports: [...byFile.values()], registrations: bindings };
}

/**
 * Renders the generated bundle — static imports, `registrations`, and the bundle applying them —
 * from its protocol, `protocols/Bundle.ts.hbs`.
 */
export function emitBundle(input: EmitInput): string {
  return renderProtocol(BUNDLE_PROTOCOL, bundleView(input));
}
